function toggleMobileDrawer(open) {
  if (open) {
    dom.mobileDrawer.classList.remove("translate-x-full");
    dom.mobileBackdrop.classList.remove("hidden");
    document.body.style.overflow = "hidden";
  } else {
    dom.mobileDrawer.classList.add("translate-x-full");
    dom.mobileBackdrop.classList.add("hidden");
    document.body.style.overflow = "";
  }
}

function initEventListeners() {
  document.querySelectorAll(".btn-lang-id").forEach(btn => btn.addEventListener("click", () => setLanguage("id")));
  document.querySelectorAll(".btn-lang-en").forEach(btn => btn.addEventListener("click", () => setLanguage("en")));

  if (dom.mobileMenuBtn) dom.mobileMenuBtn.addEventListener("click", () => toggleMobileDrawer(true));
  if (dom.mobileMenuCloseBtn) dom.mobileMenuCloseBtn.addEventListener("click", () => toggleMobileDrawer(false));
  if (dom.mobileBackdrop) dom.mobileBackdrop.addEventListener("click", () => toggleMobileDrawer(false));

  document.querySelectorAll(".mobile-nav-link").link?.forEach?.(link => {
    link.addEventListener("click", () => toggleMobileDrawer(false));
  });

  if (dom.projectSearchInput) {
    dom.projectSearchInput.addEventListener("input", (e) => {
      state.projectSearch = e.target.value;
      renderProjects(portfolioData[state.lang].projects);
    });
  }

  if (dom.copyEmailBtn) {
    dom.copyEmailBtn.addEventListener("click", () => {
      navigator.clipboard.writeText("marissaelisabeth26@gmail.com").then(() => {
        if (dom.copyEmailFeedback) {
          dom.copyEmailFeedback.classList.remove("hidden");
          setTimeout(() => dom.copyEmailFeedback.classList.add("hidden"), 3000);
        }
      });
    });
  }

  if (dom.projectModal) dom.projectModal.addEventListener("click", (e) => { if (e.target === dom.projectModal) closeModal(); });
  if (dom.certModal) dom.certModal.addEventListener("click", (e) => { if (e.target === dom.certModal) closeModal(); });

  window.addEventListener("keydown", (e) => {
    if (e.key === "Escape" && state.activeModal) closeModal();
  });

  const sections = document.querySelectorAll("section[id]");
  const scrollTopBtn = dom.backToTopBtn;

  window.addEventListener("scroll", () => {
    const scrollY = window.pageYOffset;
    if (scrollY > 350) {
      scrollTopBtn?.classList.remove("opacity-0", "pointer-events-none", "translate-y-4");
      scrollTopBtn?.classList.add("opacity-100", "pointer-events-auto", "translate-y-0");
    } else {
      scrollTopBtn?.classList.add("opacity-0", "pointer-events-none", "translate-y-4");
      scrollTopBtn?.classList.remove("opacity-100", "pointer-events-auto", "translate-y-0");
    }

    sections.forEach(sec => {
      const height = sec.offsetHeight;
      const top = sec.offsetTop - 120;
      const id = sec.getAttribute("id");
      document.querySelectorAll(`a[href="#${id}"]`).forEach(link => {
        if (scrollY > top && scrollY <= top + height) {
          if (link.classList.contains("desktop-nav-link")) link.classList.add("nav-active");
        } else {
          if (link.classList.contains("desktop-nav-link")) link.classList.remove("nav-active");
        }
      });
    });
  });

  const scrollToTop = () => window.scrollTo({ top: 0, behavior: "smooth" });
  scrollTopBtn?.addEventListener("click", scrollToTop);
  dom.footerScrollTopBtn?.addEventListener("click", scrollToTop);
}

document.addEventListener("DOMContentLoaded", () => {
  initEventListeners();
  setLanguage(state.lang);
});